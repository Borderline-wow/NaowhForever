"""Build the town map's spirit healers from Wowhead Forever.

Forever's C_DeathInfo.GetGraveyardsForMap returns nothing while you are alive, so the town map
cannot ask the game. Every graveyard's healer is the one Spirit Healer NPC, whose Wowhead page
has where each one stands (g_mapperData), as the mailboxes' pages do; spawns a step apart are
one healer, merged as Tools/build/mailboxes.py does.

Writes NaowhForever_QoL/Interface/TownSpiritHealers.lua.

Usage: python Tools/build/spirit_healers.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
from journal import ROOT, header, write  # noqa: E402
from mailboxes import merge, positions  # noqa: E402

OUT = ROOT / "NaowhForever_QoL" / "Interface" / "TownSpiritHealers.lua"
SPIRIT_HEALER = 6491   # the NPC


def main():
    by_map = merge([positions(SPIRIT_HEALER, "npc")])
    # [uiMapID] = { { x, y, "spirit", name, title, class, factions }, ... }, as
    # TownData.lua lists its NPCs, from Wowhead Forever. x and y are map percentages.
    lines = header(OUT.name, "spirit healers on the town map, by world map, generated by Tools/build/spirit_healers.py")
    lines.append("ns.TownSpiritHealers = {")
    total = 0
    for map_id in sorted(by_map):
        lines.append(f"    [{map_id}] = {{")
        for x, y in sorted(by_map[map_id]):
            lines.append(f'        {{ {x:g}, {y:g}, "spirit", "Spirit Healer", "Graveyard", nil, "AH" }},')
            total += 1
        lines.append("    },")
    lines.append("}")
    write(OUT, lines)
    print(f"{total} spirit healers on {len(by_map)} maps -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
